const listeners = new Set();
export const i18n = {
  get lang() { return lang; },
  t(key, vars) { let s = STR[lang][key] ?? STR.en[key] ?? key; if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? ''); return s; },
  set(next) { lang = next; try { localStorage.setItem('keylight.lang', lang); } catch { /* ignore */ } this.apply(); listeners.forEach((fn) => fn(lang)); },
  toggle() { this.set(lang === 'en' ? 'ja' : 'en'); },
  onChange(fn) { listeners.add(fn); },
  apply(root = document) { document.documentElement.lang = lang; root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = this.t(el.dataset.i18n); }); },
  keys: (l) => Object.keys(STR[l]),
};

let lang = 'en';
try { lang = localStorage.getItem('clipsim.lang') || (navigator.language?.startsWith('ja') ? 'ja' : 'en'); } catch { /* storage unavailable */ }
const listeners = new Set();

export const i18n = {
  get lang() { return lang; },
  t(key) { return STR[lang][key] ?? STR.en[key] ?? key; },
  set(next) {
    lang = next;
    try { localStorage.setItem('clipsim.lang', lang); } catch { /* ignore */ }
    this.apply();
    listeners.forEach((fn) => fn(lang));
  },
  toggle() { this.set(lang === 'en' ? 'ja' : 'en'); },
  onChange(fn) { listeners.add(fn); },
  apply(root = document) {
    document.documentElement.lang = lang;
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = this.t(el.dataset.i18n); });
  },
};

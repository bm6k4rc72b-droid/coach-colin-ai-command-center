#!/usr/bin/env node
/**
 * Writes the 50-agent marketing team (plus the CEO) to .claude/agents/ as Claude Code subagents.
 * Source of truth: public/colin-os/js/team.js. Run after editing the team: `npm run agents:colin-os`.
 */
import { mkdir, writeFile, readdir, unlink, readFile } from 'node:fs/promises';
import { DEPARTMENTS, ALL_AGENTS } from '../public/colin-os/js/team.js';

const DIR = new URL('../.claude/agents/', import.meta.url);
await mkdir(DIR, { recursive: true });
const MARK = '<!-- generated by scripts/colin-os-agents.mjs -->';

// Remove files we generated before (keeps hand-written agents).
for (const f of await readdir(DIR)) {
  if (f.endsWith('.md') && (await readFile(new URL(f, DIR), 'utf8')).includes(MARK)) await unlink(new URL(f, DIR));
}

const shared = `Before anything else, read \`docs/marketing-team/BRAND.md\` for the businesses, voice and guardrails. If the task
does not say which business it is for (Coach Colin or the beauty store), ask.`;

for (const a of ALL_AGENTS) {
  const body = `---
name: ${a.id}
description: ${a.deptName} specialist. ${a.does}. Use proactively when a marketing task needs this; the ceo agent delegates here.
---
${MARK}
You are **${a.id}**, part of the ${a.deptName} department of a 50-agent marketing team led by the \`ceo\` agent.

**Your job:** ${a.does}.

${shared}

**Skills to load first** (in \`.claude/skills/\`): ${a.skills.map((s) => `\`${s}\``).join(', ')}. Follow their method.

**How you work**
1. Restate the goal in one line and name what you need. If an input is missing, say MISSING rather than invent it.
2. Do the work. Prefer real data (files in this repo, pasted analytics, connected tools) over assumptions, and label
   anything that is an estimate.
3. Return: the deliverable, the 1–3 decisions the human must make, and which teammate should pick it up next.

Keep to your lane; hand off instead of doing another department's job.
`;
  await writeFile(new URL(`${a.id}.md`, DIR), body);
}

const roster = DEPARTMENTS.map((d) => `- **${d.name}:** ${d.agents.map((a) => `\`${a.id}\``).join(', ')}`).join('\n');
await writeFile(new URL('ceo.md', DIR), `---
name: ceo
description: Marketing CEO. Coordinates the 50-agent marketing team and turns a business goal into delegated work and a single plan. Use for any broad marketing goal ("grow the beauty store on TikTok Shop", "launch my coaching offer").
---
${MARK}
You are the **CEO** of a 50-agent marketing team (10 departments x 5 specialists).

${shared}

**Your team**
${roster}

**How you run a goal**
1. Turn the goal into a measurable outcome and a deadline. Ask at most 2 questions if the goal is unclear.
2. Pick the 3–8 specialists who move that outcome most. Delegate to them in parallel where their work is
   independent, in sequence where one needs another's output (research → strategy → content → conversion → analytics).
3. Give each a precise brief: business, audience, inputs, the exact deliverable, and the guardrails that apply.
4. Send drafts through \`marketing-qa\` before presenting them.
5. Return one plan: what was produced, what ships this week, the decisions only the human can make, and the metric
   you will check next.

You decide and coordinate; specialists produce. Nothing is posted, sent or spent without the human's approval.
`);
console.log(`Wrote ${ALL_AGENTS.length + 1} agents to .claude/agents/`);
